import AppKit
import CryptoKit
import Observation
import Photos
import UniformTypeIdentifiers

@MainActor
@Observable
final class ClipboardStore {
    private(set) var items: [ClipItem] = []

    var isPaused = UserDefaults.standard.bool(forKey: "isPaused") {
        didSet { UserDefaults.standard.set(isPaused, forKey: "isPaused") }
    }

    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private let historyURL: URL
    @ObservationIgnored private let imagesDirectory: URL
    @ObservationIgnored private let pasteboardDirectory: URL
    @ObservationIgnored private let imageCache = NSCache<NSString, NSImage>()
    @ObservationIgnored private var appIconCache: [String: NSImage] = [:]

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
    ]

    private static let photosAssetType = NSPasteboard.PasteboardType("com.apple.photos.object-reference.asset")
    private static let jpegType = NSPasteboard.PasteboardType("public.jpeg")
    private static let iconType = NSPasteboard.PasteboardType("com.apple.icns")
    private static let maxSavedPasteboardBytes = 50 * 1024 * 1024

    var historyLimit: Int {
        let value = UserDefaults.standard.integer(forKey: "historyLimit")
        return value > 0 ? value : 200
    }

    init() {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Clipboard", isDirectory: true)
        historyURL = base.appendingPathComponent("history.json")
        imagesDirectory = base.appendingPathComponent("Images", isDirectory: true)
        pasteboardDirectory = base.appendingPathComponent("Pasteboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true)
        try? FileManager.default.createDirectory(at: pasteboardDirectory, withIntermediateDirectories: true)
        lastChangeCount = NSPasteboard.general.changeCount
        load()
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.1
    }

    // MARK: - Capture

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard !isPaused else { return }

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        guard var item = makeItem(from: pasteboard, types: types) else { return }
        if [.image, .video, .file].contains(item.kind) {
            item.pasteboardFile = savePasteboard(pasteboard, as: item.hash)
        }

        let app = NSWorkspace.shared.frontmostApplication
        item.sourceApp = app?.localizedName
        item.sourceBundleID = app?.bundleIdentifier
        insert(item)
    }

    private func makeItem(from pasteboard: NSPasteboard, types: Set<NSPasteboard.PasteboardType>) -> ClipItem? {
        if types.contains(Self.photosAssetType), let item = makePhotosItem(from: pasteboard) {
            return item
        }
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            return ClipItem(kind: .file, filePaths: paths, hash: Self.hash(paths.joined(separator: "\n")), date: .now)
        }

        let string = pasteboard.string(forType: .string)
        let trimmed = string?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        let hasImage = types.contains(.png) || types.contains(.tiff)

        if hasImage, trimmed.isEmpty || Self.isLink(trimmed), let item = makeImageItem(from: pasteboard) {
            return item
        }
        if let string, !trimmed.isEmpty {
            return ClipItem(kind: Self.isLink(trimmed) ? .link : .text, text: string, hash: Self.hash(string), date: .now)
        }
        return hasImage ? makeImageItem(from: pasteboard) : nil
    }

    private func makeImageItem(from pasteboard: NSPasteboard) -> ClipItem? {
        guard let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: data),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        let hash = Self.hash(png)
        let name = "\(hash).png"
        let url = imagesDirectory.appendingPathComponent(name)
        if !FileManager.default.fileExists(atPath: url.path) {
            try? png.write(to: url)
        }
        return ClipItem(
            kind: .image,
            imageFile: name,
            imageWidth: Double(rep.pixelsWide),
            imageHeight: Double(rep.pixelsHigh),
            hash: hash,
            date: .now
        )
    }

    // Photos copies a reference to each asset, which apps use to paste the original photo or video,
    // next to a small preview whose dimensions say nothing about the original.
    private func makePhotosItem(from pasteboard: NSPasteboard) -> ClipItem? {
        let assets = (pasteboard.pasteboardItems ?? []).compactMap {
            $0.propertyList(forType: Self.photosAssetType) as? [String: Any]
        }
        guard !assets.isEmpty else { return nil }
        let isVideo = assets.allSatisfy { $0["mediaType"] as? Int == PHAssetMediaType.video.rawValue }

        var item = makeImageItem(from: pasteboard) ?? ClipItem(kind: .image, hash: "", date: .now)
        item.kind = isVideo ? .video : .image
        item.itemCount = assets.count
        item.imageWidth = nil
        item.imageHeight = nil
        item.hash = Self.hash(assets.compactMap { $0["localIdentifier"] as? String }.joined(separator: "\n"))
        return item
    }

    private func savePasteboard(_ pasteboard: NSPasteboard, as name: String) -> String? {
        var saved: [[SavedRepresentation]] = []
        var totalBytes = 0
        for pasteboardItem in pasteboard.pasteboardItems ?? [] {
            let representations = Self.representations(of: pasteboardItem)
            totalBytes += representations.reduce(0) { $0 + $1.data.count }
            guard totalBytes <= Self.maxSavedPasteboardBytes else { return nil }
            if !representations.isEmpty { saved.append(representations) }
        }

        let encoder = PropertyListEncoder()
        encoder.outputFormat = .binary
        let url = pasteboardDirectory.appendingPathComponent("\(name).plist")
        guard !saved.isEmpty,
              let data = try? encoder.encode(saved),
              (try? data.write(to: url, options: .atomic)) != nil else { return nil }
        return url.lastPathComponent
    }

    private static func representations(of item: NSPasteboardItem) -> [SavedRepresentation] {
        // File promises can only be fulfilled by the app that made them, and the large icon Finder attaches to
        // every file is slow to read; pasting adds an icon back.
        let types = item.types.filter {
            !$0.rawValue.localizedCaseInsensitiveContains("promise") && $0 != iconType
        }
        // TIFF is uncompressed and macOS recreates it on demand from PNG or JPEG.
        let skipsTIFF = types.contains(.png) || types.contains(jpegType)
        return types.compactMap { type in
            if type == .tiff && skipsTIFF { return nil }
            guard let data = item.data(forType: type) else { return nil }
            if type == .tiff, let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) {
                return SavedRepresentation(type: NSPasteboard.PasteboardType.png.rawValue, data: png)
            }
            return SavedRepresentation(type: type.rawValue, data: data)
        }
    }

    private func insert(_ newItem: ClipItem) {
        var item = newItem
        var replaced: ClipItem?
        if let index = items.firstIndex(where: { $0.hash == newItem.hash }) {
            item.id = items[index].id
            item.isPinned = items[index].isPinned
            replaced = items.remove(at: index)
        }
        items.insert(item, at: 0)
        if let replaced { removeFiles(of: replaced) }
        applyLimit()
    }

    // MARK: - Actions

    func copyToPasteboard(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        if let saved = savedPasteboardItems(for: item) {
            pasteboard.writeObjects(Self.withFileIcon(saved))
        } else {
            switch item.kind {
            case .text, .link:
                pasteboard.setString(item.text ?? "", forType: .string)
            case .image, .video:
                if let image = image(for: item) { pasteboard.writeObjects([image]) }
            case .file:
                pasteboard.writeObjects(Self.withFileIcon(Self.fileItems(for: item.filePaths ?? [])))
            }
        }
        lastChangeCount = pasteboard.changeCount

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = .now
            items.insert(moved, at: 0)
            save()
        }
    }

    private static func fileItems(for paths: [String]) -> [NSPasteboardItem] {
        paths.map { path in
            let url = URL(fileURLWithPath: path)
            let item = NSPasteboardItem()
            item.setString(url.absoluteString, forType: .fileURL)
            item.setString(url.lastPathComponent, forType: .string)
            return item
        }
    }

    // Chromium-based apps only paste a copied file as an image when image data comes with it, which Finder
    // provides as the file's icon; without it they paste the file's name.
    private static func withFileIcon(_ items: [NSPasteboardItem]) -> [NSPasteboardItem] {
        let hasImage = items.contains { item in
            item.types.contains { UTType($0.rawValue)?.conforms(to: .image) == true }
        }
        guard !hasImage,
              let first = items.first,
              let url = first.string(forType: .fileURL).flatMap(URL.init(string:)),
              let path = (url as NSURL).filePathURL?.path else { return items }
        var rect = NSRect(x: 0, y: 0, width: 256, height: 256)
        if let icon = NSWorkspace.shared.icon(forFile: path).cgImage(forProposedRect: &rect, context: nil, hints: nil),
           let png = NSBitmapImageRep(cgImage: icon).representation(using: .png, properties: [:]) {
            first.setData(png, forType: .png)
        }
        return items
    }

    private func savedPasteboardItems(for item: ClipItem) -> [NSPasteboardItem]? {
        guard let name = item.pasteboardFile,
              let data = try? Data(contentsOf: pasteboardDirectory.appendingPathComponent(name)),
              let saved = try? PropertyListDecoder().decode([[SavedRepresentation]].self, from: data) else { return nil }
        return saved.map { representations in
            let pasteboardItem = NSPasteboardItem()
            for representation in representations {
                pasteboardItem.setData(representation.data, forType: .init(representation.type))
            }
            return pasteboardItem
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        removeFiles(of: item)
        save()
    }

    func clear(keepPinned: Bool = true) {
        let removed = items.filter { !keepPinned || !$0.isPinned }
        items.removeAll { !keepPinned || !$0.isPinned }
        removed.forEach(removeFiles)
        save()
    }

    func applyLimit() {
        let limit = historyLimit
        var unpinned = 0
        var removed: [ClipItem] = []
        items = items.filter { item in
            guard !item.isPinned else { return true }
            unpinned += 1
            if unpinned > limit {
                removed.append(item)
                return false
            }
            return true
        }
        removed.forEach(removeFiles)
        save()
    }

    // MARK: - Media

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = imageCache.object(forKey: name as NSString) { return cached }
        guard let image = NSImage(contentsOf: imagesDirectory.appendingPathComponent(name)) else { return nil }
        imageCache.setObject(image, forKey: name as NSString)
        return image
    }

    func appIcon(for bundleID: String?) -> NSImage? {
        guard let bundleID else { return nil }
        if let cached = appIconCache[bundleID] { return cached }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        appIconCache[bundleID] = icon
        return icon
    }

    func imageFileSize(for item: ClipItem) -> Int64? {
        guard let name = item.imageFile else { return nil }
        let attributes = try? FileManager.default.attributesOfItem(atPath: imagesDirectory.appendingPathComponent(name).path)
        return (attributes?[.size] as? NSNumber)?.int64Value
    }

    private func removeFiles(of item: ClipItem) {
        if let name = item.imageFile, !items.contains(where: { $0.imageFile == name }) {
            imageCache.removeObject(forKey: name as NSString)
            try? FileManager.default.removeItem(at: imagesDirectory.appendingPathComponent(name))
        }
        if let name = item.pasteboardFile, !items.contains(where: { $0.pasteboardFile == name }) {
            try? FileManager.default.removeItem(at: pasteboardDirectory.appendingPathComponent(name))
        }
    }

    // MARK: - Persistence

    private func load() {
        guard let data = try? Data(contentsOf: historyURL) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        items = (try? decoder.decode([ClipItem].self, from: data)) ?? []
    }

    private func save() {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        guard let data = try? encoder.encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }

    // MARK: - Helpers

    private static func hash(_ string: String) -> String { hash(Data(string.utf8)) }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private static func isLink(_ string: String) -> Bool {
        guard !string.contains(where: \.isWhitespace),
              let url = URL(string: string),
              let scheme = url.scheme?.lowercased() else { return false }
        if scheme == "mailto" { return true }
        return ["http", "https", "ftp"].contains(scheme) && url.host != nil
    }
}

private struct SavedRepresentation: Codable {
    var type: String
    var data: Data
}
